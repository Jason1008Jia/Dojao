package com.dojao.jdbc;

import com.dojao.core.rpc.FlightActions;
import com.dojao.core.rpc.QueryRequest;
import com.dojao.core.rpc.QueryResponse;
import com.google.protobuf.InvalidProtocolBufferException;
import org.apache.arrow.flight.Action;
import org.apache.arrow.flight.FlightClient;
import org.apache.arrow.flight.FlightRuntimeException;
import org.apache.arrow.flight.Result;

import java.sql.*;
import java.util.Iterator;

/**
 * JDBC Statement 实现，通过 Arrow Flight（doAction "execute_query"）将 SQL 发送到 Master。
 */
public class DojaoStatement implements Statement {

    final DojaoConnection connection;
    DojaoResultSet currentResultSet;
    int updateCount = -1;
    boolean closed;
    int maxRows;
    int queryTimeout;

    DojaoStatement(DojaoConnection connection) {
        this.connection = connection;
    }

    // ==================== executeQuery ====================

    @Override
    public ResultSet executeQuery(String sql) throws SQLException {
        checkClosed();
        QueryResponse resp = executeRpc(sql);
        closeCurrentResultSet();
        currentResultSet = new DojaoResultSet(this, resp);
        return currentResultSet;
    }

    // ==================== execute ====================

    @Override
    public boolean execute(String sql) throws SQLException {
        checkClosed();
        QueryResponse resp = executeRpc(sql);
        closeCurrentResultSet();
        currentResultSet = new DojaoResultSet(this, resp);
        return true;
    }

    // ==================== executeUpdate ====================

    @Override
    public int executeUpdate(String sql) throws SQLException {
        execute(sql);
        updateCount = 0;
        return updateCount;
    }

    // ==================== Batch ====================

    @Override
    public int[] executeBatch() throws SQLException { throw DojaoConnection.notSupported(); }
    @Override
    public void addBatch(String sql) throws SQLException { throw DojaoConnection.notSupported(); }
    @Override
    public void clearBatch() { /* no-op */ }

    // ==================== Results ====================

    @Override public ResultSet getResultSet() { return currentResultSet; }
    @Override public int getUpdateCount() { return updateCount; }

    @Override
    public boolean getMoreResults() throws SQLException {
        closeCurrentResultSet();
        return false;
    }

    @Override public boolean getMoreResults(int current) throws SQLException { return getMoreResults(); }
    @Override public ResultSet getGeneratedKeys() throws SQLException { throw DojaoConnection.notSupported(); }

    // ==================== Close ====================

    @Override
    public void close() throws SQLException {
        closeCurrentResultSet();
        closed = true;
    }

    @Override public boolean isClosed() { return closed; }

    // ==================== Settings ====================

    @Override public void setMaxFieldSize(int max) { /* no-op */ }
    @Override public int getMaxFieldSize() { return 0; }
    @Override public int getMaxRows() { return maxRows; }
    @Override public void setMaxRows(int max) { this.maxRows = max; }
    @Override public int getQueryTimeout() { return queryTimeout; }
    @Override public void setQueryTimeout(int seconds) { this.queryTimeout = seconds; }
    @Override public void cancel() { /* Flight doAction 阻塞调用无法中途取消 */ }
    @Override public void setCursorName(String name) { /* no-op */ }
    @Override public void setEscapeProcessing(boolean enable) { /* no-op */ }
    @Override public int getFetchDirection() { return ResultSet.FETCH_FORWARD; }
    @Override public void setFetchDirection(int direction) { /* no-op */ }
    @Override public int getFetchSize() { return 0; }
    @Override public void setFetchSize(int rows) { /* no-op */ }
    @Override public boolean isPoolable() { return false; }
    @Override public void setPoolable(boolean poolable) { /* no-op */ }
    @Override public void closeOnCompletion() { /* no-op */ }
    @Override public boolean isCloseOnCompletion() { return false; }
    @Override public int getResultSetHoldability() { return ResultSet.CLOSE_CURSORS_AT_COMMIT; }
    @Override public int getResultSetType() { return ResultSet.TYPE_FORWARD_ONLY; }
    @Override public int getResultSetConcurrency() { return ResultSet.CONCUR_READ_ONLY; }

    // ==================== Connection ====================

    @Override public Connection getConnection() { return connection; }
    @Override public SQLWarning getWarnings() { return null; }
    @Override public void clearWarnings() { /* no-op */ }

    // ==================== Unsupported overloads ====================

    @Override public boolean execute(String sql, int autoGeneratedKeys) throws SQLException { throw DojaoConnection.notSupported(); }
    @Override public boolean execute(String sql, int[] columnIndexes) throws SQLException { throw DojaoConnection.notSupported(); }
    @Override public boolean execute(String sql, String[] columnNames) throws SQLException { throw DojaoConnection.notSupported(); }
    @Override public int executeUpdate(String sql, int autoGeneratedKeys) throws SQLException { throw DojaoConnection.notSupported(); }
    @Override public int executeUpdate(String sql, int[] columnIndexes) throws SQLException { throw DojaoConnection.notSupported(); }
    @Override public int executeUpdate(String sql, String[] columnNames) throws SQLException { throw DojaoConnection.notSupported(); }

    @Override public <T> T unwrap(Class<T> iface) throws SQLException { throw DojaoConnection.notSupported(); }
    @Override public boolean isWrapperFor(Class<?> iface) { return false; }

    // ==================== Internal ====================

    private QueryResponse executeRpc(String sql) throws SQLException {
        try {
            QueryRequest request = QueryRequest.newBuilder().setSql(sql).build();
            Iterator<Result> results = connection.client()
                    .doAction(new Action(FlightActions.EXECUTE_QUERY, request.toByteArray()));
            if (!results.hasNext()) {
                throw new SQLException("Master 未返回结果");
            }
            return QueryResponse.parseFrom(results.next().getBody());
        } catch (FlightRuntimeException e) {
            throw new SQLException("Query execution failed: " + e.status().description(), e);
        } catch (InvalidProtocolBufferException e) {
            throw new RuntimeException(e);
        }
    }

    void closeCurrentResultSet() {
        if (currentResultSet != null) {
            currentResultSet.close();
            currentResultSet = null;
        }
    }

    void checkClosed() throws SQLException {
        if (closed) throw new SQLException("Statement is closed");
    }
}
